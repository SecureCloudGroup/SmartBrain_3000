// Codegen for the NI form painter: emits src/lib/ni/tokens.ts and src/lib/ni/icons.generated.ts
// from the Python-owned ni_forms/tokens.json + assets/icons.json, and fills the three
// `ni-tokens:*` marker regions in src/app.css with the `--ni-<name>` custom properties for
// both themes. The CLIR carries token NAMES; only the painter resolves them to CSS vars.
// Rerun after a tokens.json or icons.json change:  node scripts/gen-ni-tokens.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const niDir = join(here, "..", "..", "app", "smartbrain_3000", "ni_forms");
const tokensJson = join(niDir, "tokens.json");
const iconsJson = join(niDir, "assets", "icons.json");
const outTokens = join(here, "..", "src", "lib", "ni", "tokens.ts");
const outIcons = join(here, "..", "src", "lib", "ni", "icons.generated.ts");
const appCss = join(here, "..", "src", "app.css");

const raw = JSON.parse(readFileSync(tokensJson, "utf8"));
const dark = raw.color.dark;
const light = raw.color.light;
const names = Object.keys(dark).sort();
if (JSON.stringify(Object.keys(light).sort()) !== JSON.stringify(names)) {
  console.error("tokens.json: dark and light must define the same token set");
  process.exit(1);
}

// '#rrggbb' or '#rrggbb@a' -> hex or rgba(), mirroring ni_forms.tokens.css().
function cssColour(value) {
  const [hex, alpha] = value.split("@");
  if (!/^#[0-9a-f]{6}$/i.test(hex)) {
    console.error(`bad colour literal: ${value}`);
    process.exit(1);
  }
  if (alpha === undefined) return hex.toLowerCase();
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return `rgba(${r},${g},${b},${Number(alpha)})`;
}

const declLines = (theme) => names.map((n) => `--ni-${n}: ${cssColour(theme[n])};`);
const typeRoles = Object.fromEntries(Object.entries(raw.type).filter(([k]) => !k.startsWith("_")));
const dumpJson = (v) => JSON.stringify(v, null, 2);

const tokensBody =
  "// GENERATED by web/scripts/gen-ni-tokens.mjs from app/smartbrain_3000/ni_forms/tokens.json.\n" +
  "// Do not edit by hand; rerun the generator after a tokens.json change.\n" +
  "// CLIR prims name tokens (e.g. 'viz-line'); only the painter resolves them to CSS vars.\n" +
  "\n" +
  `export const NI_TOKEN_NAMES = ${dumpJson(names)} as const;\n` +
  "\n" +
  "export type NiTokenName = (typeof NI_TOKEN_NAMES)[number];\n" +
  "\n" +
  "const NAMES_SET: ReadonlySet<string> = new Set(NI_TOKEN_NAMES);\n" +
  "\n" +
  "export function isTokenName(x: unknown): x is NiTokenName {\n" +
  "  console.assert(NAMES_SET.size > 0, \"isTokenName: token set loaded\");\n" +
  "  return typeof x === \"string\" && NAMES_SET.has(x);\n" +
  "}\n" +
  "\n" +
  "export interface NiTypeRole {\n" +
  "  px: number; wt: number; lh: number; tnum: boolean;\n" +
  "  ladder?: readonly number[];\n" +
  "  max_lines?: number;\n" +
  "}\n" +
  "\n" +
  `export const NI_TYPE: Record<string, NiTypeRole> = ${dumpJson(typeRoles)};\n` +
  "\n" +
  `export const NI_VIZ = ${dumpJson(raw.viz)} as const;\n` +
  "\n" +
  "/** The custom-property declarations per theme, exactly as app.css carries them. */\n" +
  "export const NI_CSS_DARK = `\n" + declLines(dark).map((l) => `  ${l}`).join("\n") + "\n`;\n" +
  "\n" +
  "export const NI_CSS_LIGHT = `\n" + declLines(light).map((l) => `  ${l}`).join("\n") + "\n`;\n";
writeFileSync(outTokens, tokensBody);
console.log(`ni tokens: ${names.length} names, ${Object.keys(typeRoles).length} roles -> src/lib/ni/tokens.ts`);

// app.css: fill each marker region, keeping the region's own indentation.
function fillRegion(css, name, lines) {
  const start = new RegExp(`^([ \\t]*)/\\* ${name}:start[\\s\\S]*?\\*/\\n`, "m");
  const end = new RegExp(`^[ \\t]*/\\* ${name}:end \\*/`, "m");
  const ms = start.exec(css);
  const me = end.exec(css);
  if (!ms || !me || me.index < ms.index) {
    console.error(`app.css: marker region ${name} missing`);
    process.exit(1);
  }
  const head = css.slice(0, ms.index + ms[0].length);
  const body = lines.map((l) => `${ms[1]}${l}`).join("\n") + "\n";
  return head + body + css.slice(me.index);
}
let css = readFileSync(appCss, "utf8");
css = fillRegion(css, "ni-tokens:dark", declLines(dark));
css = fillRegion(css, "ni-tokens:light", declLines(light));
css = fillRegion(css, "ni-tokens:light-system", declLines(light));
writeFileSync(appCss, css);
console.log("ni tokens: 3 regions filled in src/app.css");

// Icons: frozen first-party outlines (ICONS enum in types.py).
const iconsRaw = JSON.parse(readFileSync(iconsJson, "utf8"));
const iconsBody =
  "// GENERATED by web/scripts/gen-ni-tokens.mjs from app/smartbrain_3000/ni_forms/assets/icons.json.\n" +
  "// Frozen first-party icon outlines (ICONS enum from types.py); do not edit by hand.\n" +
  "\n" +
  "export interface NiIconCircleEl { t: \"circle\"; c: [number, number]; r: number; fill: boolean }\n" +
  "export interface NiIconPolyEl { t: \"poly\"; pts: Array<[number, number]>; closed: boolean; fill: boolean }\n" +
  "export type NiIconEl = NiIconCircleEl | NiIconPolyEl;\n" +
  "\n" +
  "export interface NiIconSet {\n" +
  "  box: number; stroke: number; icons: Record<string, readonly NiIconEl[]>;\n" +
  "}\n" +
  "\n" +
  `export const NI_ICONS: NiIconSet = ${JSON.stringify(iconsRaw)};\n`;
writeFileSync(outIcons, iconsBody);
console.log(`ni icons: ${Object.keys(iconsRaw.icons).length} outlines -> src/lib/ni/icons.generated.ts`);
