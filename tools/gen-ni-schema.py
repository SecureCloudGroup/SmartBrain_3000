#!/usr/bin/env python3
"""Generate the NI wire-contract JSON Schema and the Python and TypeScript types cut from it (plan S6b, D7).

One schema describes what the web reads from the Neural Interface backend: the board row, the flow field
(state, actions, progress, question, suggestions, awaiting_yes), the action and card vocabularies, the
quality tier and the sealed ``recipe`` block. Every vocabulary is read from the Python constant that owns
it (``ni_master``, ``ni_recipe``, ``ni``, ``ni_flow``, ``ni_forms.types``), so a new action kind or tier
reaches both type files by regeneration. Only the object shapes are declared here.

  python tools/gen-ni-schema.py           write the three generated files
  python tools/gen-ni-schema.py --check   exit 1 when any of them differs from what the sources produce

Generated (all committed; CI runs --check beside the committed-bundle check):
  app/smartbrain_3000/ni_schema.json      the schema
  app/smartbrain_3000/ni_types_gen.py     TypedDicts and Literals
  web/src/lib/ni/types.gen.ts             interfaces, unions and const vocabularies

Standard library only. ``validate`` is a small checker for the schema subset this script emits.
"""
from __future__ import annotations

import json
import keyword
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "app"))

from smartbrain_3000 import ni, ni_flow, ni_master, ni_recipe
from smartbrain_3000.ni_forms import types as ni_form_types

OUT_SCHEMA = ROOT / "app" / "smartbrain_3000" / "ni_schema.json"
OUT_PY = ROOT / "app" / "smartbrain_3000" / "ni_types_gen.py"
OUT_TS = ROOT / "web" / "src" / "lib" / "ni" / "types.gen.ts"
HEADER = "GENERATED by tools/gen-ni-schema.py from the NI Python sources. Do not edit; rerun the script."

# ---- schema builders ------------------------------------------------------------------------------------


def ref(name: str) -> dict:
    return {"$ref": f"#/$defs/{name}"}


def enum(values: object) -> dict:
    return {"enum": sorted(values)}  # type: ignore[type-var]


def obj(props: dict[str, dict], *, opt: tuple[str, ...] = (), desc: str = "") -> dict:
    """A closed object: every property required except those named in ``opt``."""
    assert set(opt) <= set(props), "optional names are properties"
    out: dict[str, Any] = {"type": "object", "properties": props, "additionalProperties": False,
                           "required": [k for k in props if k not in opt]}
    if desc:
        out["description"] = desc
    return out


def arr(item: dict, **bounds: int) -> dict:
    return {"type": "array", "items": item, **bounds}


def nullable(s: dict) -> dict:
    return {"anyOf": [s, {"type": "null"}]}


STR: dict = {"type": "string"}
INT: dict = {"type": "integer"}
BOOL: dict = {"type": "boolean"}


def text(n: int) -> dict:
    return {"type": "string", "minLength": 0, "maxLength": n}


def _same(found: frozenset[str], declared: dict, what: str) -> None:
    """The shapes below are declared by hand; fail generation when a source's closed key set moves."""
    assert found == set(declared["properties"]), f"{what}: ni_recipe keys changed, update the schema shape"


def _flow_defs() -> dict[str, dict]:
    suggestion = obj({"title": STR, "host": STR, "url": STR, "kind": enum({"library", "link"}),
                      "found": enum({"dataset", "page"}), "evidence": arr(STR), "needs": arr(enum({"key", "contact"}))},
                     opt=("kind", "found", "evidence", "needs"))
    progress = obj({"step": INT, "of": INT, "label": STR, "gate": STR, "try": ref("FlowTry")}, opt=("gate", "try"))
    question = obj({"kind": ref("FlowQuestionKind"), "prompt": STR, "model": STR, "local": STR},
                   opt=("prompt", "model", "local"))
    flow = obj({"state": ref("FlowState"), "error": STR, "actions": arr(ref("ActionKind")),
                "progress": ref("FlowProgress"), "suggestions": arr(ref("Suggestion")), "reason": STR,
                "question": ref("FlowQuestion"), "reopen": arr(ref("ReopenKind")), "access": ref("FlowAccess"),
                "tap": ref("FlowTap"), "browser": ref("FlowBrowser")},
               opt=("error", "actions", "progress", "suggestions", "reason", "question", "reopen", "access",
                    "tap", "browser"),
               desc="The flow field of a board row: present while a card builds or after it ended abnormally.")
    return {
        "Suggestion": suggestion, "FlowProgress": progress, "FlowTry": obj({"n": INT, "of": INT, "host": STR}),
        "FlowQuestion": question,
        "FlowAccess": obj({"host": STR, "provider": STR, "key": nullable(ref("FlowDocsKey")), "contact": BOOL}),
        "FlowDocsKey": obj({"docs_url": STR}),
        "FlowTap": obj({"render_notice": BOOL, "site_cap": INT}), "FlowBrowser": obj({"phase": STR, "pct": INT}),
        "Flow": flow,
    }


def _row_defs() -> dict[str, dict]:
    row = obj({
        "id": STR, "title": STR, "state": ref("ItemState"), "enabled": BOOL, "interval_minutes": INT,
        "last_checked": nullable(STR), "last_status": STR, "consecutive_failures": INT, "position": INT,
        "display": ref("Display"), "interpreted": BOOL, "template_update": BOOL, "template_gone": BOOL,
        "needs_credentials": arr(ref("NeedsItem")), "needs_params": arr(ref("NeedsItem")),
        "l2_proposal": BOOL, "c2_ok": BOOL, "awaiting_yes": nullable(ref("AwaitingYes")), "shell": BOOL,
        "born": STR, "flow": nullable(ref("Flow")),
        "payload_slot": nullable(enum({"latest", "last_good", "preview"})), "payload_at": nullable(STR),
        "payload_ok": nullable(BOOL), "payload": {},
        "interpretation": STR, "query": ref("RowQuery"), "fit": ref("Fit"), "actions": arr(ref("ActionKind")),
        "rendered": BOOL, "render": nullable(ref("RowRender")), "draft": nullable(ref("RowDraft")),
        "preview": nullable(ref("RowPreview")),
    }, opt=("interpretation", "query", "fit", "actions", "rendered", "render", "draft", "preview"),
        desc="One row of GET /api/ni/board. `actions` is present only under the v2 flow; `payload` is the bound scene.")
    return {
        "NeedsItem": obj({"name": STR, "label": STR}), "Display": obj({"size": ref("DisplaySize")}),
        "AwaitingYes": obj({"from": enum({"page", "dataset", "library"}), "host": STR, "title": STR, "used_key": BOOL},
                           opt=("used_key",)),
        "Fit": obj({"verdict": enum({"no", "partly"}), "missing": arr(STR)}),
        "FeedCandidate": obj({"url": STR, "site": STR}),
        "RowRender": obj({"sites": arr(STR), "unavailable": BOOL}),
        "RowDraft": obj({"reason": enum({"render_sites"}), "sites": arr(STR)}),
        "RowPreview": obj({"feed_candidates": arr(ref("FeedCandidate"))}),
        "RowQuery": obj({"coverage": {"type": "object", "additionalProperties": STR}}, opt=("coverage",)),
        "BoardRow": row,
        "FlowPoll": obj({"id": STR, "state": ref("ItemState"), "flow": nullable(ref("Flow")),
                         "awaiting_yes": nullable(ref("AwaitingYes")), "actions": arr(ref("ActionKind"))},
                        desc="GET /api/ni/items/{id}/flow (v2): one item's flow fields."),
    }


def _recipe_defs() -> dict[str, dict]:
    scalar = {"anyOf": [BOOL, {"type": "number"}, text(200)]}
    question = obj({
        "kind": ref("RecipeQuestionKind"), "subject": {"type": "string", "minLength": 1, "maxLength": 120},
        "places": arr(text(80), maxItems=ni_recipe.MAX_LIST), "entities": arr(text(80), maxItems=ni_recipe.MAX_LIST),
        "window": nullable(ref("RecipeWindow")), "threshold": nullable(ref("RecipeThreshold")),
        "order": arr(ref("RecipeOrder"), maxItems=3), "limit": nullable({"type": "integer", "minimum": 1, "maximum": 100}),
        "compare_count": {"type": "integer", "minimum": 0, "maximum": ni_recipe.MAX_LIST},
        "units": nullable(text(20)), "cadence": nullable(ref("Cadence")),
    })
    _same(ni_recipe._QUESTION_KEYS, question, "recipe.question")
    source = obj({"kind": ref("SourceKind"), "ref": text(300), "host": text(253), "why": text(200)})
    check = obj({"check": ref("RecipeCheckName"), "ok": BOOL, "reason": text(120)})
    verification = obj({"verdict": ref("Verdict"), "checks": arr(ref("RecipeCheck"), maxItems=ni_recipe.MAX_CONSTRAINTS),
                        "verified_at": {"type": "string", "minLength": 1, "maxLength": 40},
                        "fetches": {"type": "integer", "minimum": 0, "maximum": 8}})
    budget = obj({k: {"type": "integer", "minimum": 0, "maximum": 100000} for k in sorted(ni_recipe._BUDGET_KEYS)})
    research = obj({"turns": arr(ref("RecipeTurn"), maxItems=ni_recipe.MAX_TURNS), "budget": ref("RecipeBudget")})
    recipe = obj({
        "question": ref("RecipeQuestion"),
        "sources": arr(ref("RecipeSource"), minItems=1, maxItems=ni_recipe.MAX_SOURCES),
        "constraints": arr(ref("RecipeConstraint"), maxItems=ni_recipe.MAX_CONSTRAINTS),
        "tier": ref("QualityTier"), "verification": ref("RecipeVerification"),
        "provenance": ref("RecipeProvenance"), "research": ref("RecipeResearch"),
    }, opt=("verification", "provenance", "research"),
        desc="The sealed recipe block of a researched card (spec.recipe); system-owned, never in a template pack.")
    _same(ni_recipe._RECIPE_KEYS, recipe, "recipe")
    return {
        "Scalar": scalar, "RecipeQuestion": question,
        "RecipeWindow": obj({"from": nullable(text(20)), "to": nullable(text(20))}),
        "RecipeThreshold": obj({"op": ref("Op"), "value": ref("Scalar")}),
        "RecipeOrder": obj({"col": text(200), "dir": ref("Dir")}),
        "RecipeSource": source, "RecipeConstraint": obj({"check": ref("RecipeCheckName"), "value": nullable(ref("Scalar"))}),
        "RecipeCheck": check, "RecipeVerification": verification,
        "RecipeProvenance": obj({"author": ref("Author"), "built_at": {"type": "string", "minLength": 1, "maxLength": 40}}),
        "RecipeTurn": obj({"tool": ref("Tool"), "arg": text(200), "outcome": text(200)}),
        "RecipeBudget": budget, "RecipeResearch": research, "Recipe": recipe,
    }


def _inline_objects(d: dict) -> list[str]:
    """Property or item schemas that are objects with properties (the type files need them named)."""
    inner = [v for v in d.get("properties", {}).values()] + ([d["items"]] if "items" in d else [])
    inner += [x for v in inner for x in v.get("anyOf", [])] + d.get("anyOf", [])
    inner += [x["items"] for x in inner if "items" in x]
    return [x for x in inner if "properties" in x]


def build_schema() -> dict:
    """The whole schema: vocabularies from the Python constants, shapes declared above."""
    defs: dict[str, dict] = {
        "ItemState": enum(ni._STATES), "DisplaySize": enum(ni._DISPLAY_SIZES), "FlowState": enum(ni_flow.FLOW_STATES),
        "ActionKind": enum(ni_master.ACTION_KINDS), "FlowQuestionKind": enum(ni_master.QUESTION_KINDS),
        "ReopenKind": enum(ni_master.REOPEN_KINDS), "CardKind": enum(ni_form_types.KINDS),
        "QualityTier": enum(ni_recipe.QUALITY_TIERS), "RecipeQuestionKind": enum(ni_recipe.QUESTION_KINDS),
        "Cadence": enum(ni_recipe.CADENCES), "RecipeCheckName": enum(ni_recipe.CHECKS),
        "SourceKind": enum(ni_recipe.SOURCE_KINDS), "Verdict": enum(ni_recipe.VERDICTS), "Tool": enum(ni_recipe.TOOLS),
        "Op": enum(ni_recipe.OPS), "Dir": enum(ni_recipe.DIRS), "Author": enum(ni_recipe.AUTHORS),
        **_flow_defs(), **_row_defs(), **_recipe_defs(),
    }
    for name, d in defs.items():
        assert name.isidentifier(), f"def name {name} must be an identifier"
        assert "enum" in d or d.get("type") == "object" or "anyOf" in d, f"{name} has a shape"
        assert not _inline_objects(d), f"{name} nests an unnamed object; give it a def"
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "NI wire contract",
            "description": HEADER, "$defs": dict(sorted(defs.items()))}


# ---- validator (the subset above) -----------------------------------------------------------------------

_TYPES = {"string": str, "boolean": bool, "object": dict, "array": list, "null": type(None)}


def _is(value: object, kind: str) -> bool:
    if kind in ("integer", "number"):
        ok = isinstance(value, int | float) and not isinstance(value, bool)
        return ok and (kind == "number" or isinstance(value, int))
    return isinstance(value, _TYPES[kind])


def validate(value: object, schema: dict, root: dict, path: str = "$") -> list[str]:
    """Errors of ``value`` against ``schema`` (``root`` resolves ``$ref``); empty when it conforms."""
    assert isinstance(schema, dict) and isinstance(root, dict), "schemas are objects"
    if "$ref" in schema:
        return validate(value, root["$defs"][schema["$ref"].rsplit("/", 1)[1]], root, path)
    if "anyOf" in schema:
        tried = [validate(value, s, root, path) for s in schema["anyOf"]]
        return [] if any(not e for e in tried) else [f"{path}: matches none of {len(tried)} alternatives"]
    if "enum" in schema and value not in schema["enum"]:
        return [f"{path}: {value!r} is not one of {schema['enum']}"]
    kind = schema.get("type")
    if kind is not None and not _is(value, kind):
        return [f"{path}: expected {kind}, got {type(value).__name__}"]
    errors: list[str] = []
    if isinstance(value, str):
        errors += [f"{path}: length {len(value)} outside {schema.get('minLength', 0)}..{schema.get('maxLength')}"
                   for _ in [0] if len(value) < schema.get("minLength", 0) or len(value) > schema.get("maxLength", 1 << 30)]
    if isinstance(value, int | float) and not isinstance(value, bool):
        lo, hi = schema.get("minimum"), schema.get("maximum")
        if (lo is not None and value < lo) or (hi is not None and value > hi):
            errors.append(f"{path}: {value} outside {lo}..{hi}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0) or len(value) > schema.get("maxItems", 1 << 30):
            errors.append(f"{path}: {len(value)} items outside {schema.get('minItems', 0)}..{schema.get('maxItems')}")
        for i, item in enumerate(value):  # bounded by the input
            errors += validate(item, schema.get("items", {}), root, f"{path}[{i}]")
    if isinstance(value, dict):
        errors += _validate_object(value, schema, root, path)
    return errors


def _validate_object(value: dict, schema: dict, root: dict, path: str) -> list[str]:
    props = schema.get("properties", {})
    errors = [f"{path}: missing {k}" for k in schema.get("required", []) if k not in value]
    extra = schema.get("additionalProperties", True)
    for k, v in value.items():  # bounded by the input
        if k in props:
            errors += validate(v, props[k], root, f"{path}.{k}")
        elif extra is False:
            errors.append(f"{path}: unknown key {k}")
        elif isinstance(extra, dict):
            errors += validate(v, extra, root, f"{path}.{k}")
    return errors


# ---- code generation ------------------------------------------------------------------------------------


def _deps(schema: object) -> set[str]:
    if isinstance(schema, dict):
        found = {schema["$ref"].rsplit("/", 1)[1]} if "$ref" in schema else set()
        for v in schema.values():
            found |= _deps(v)
        return found
    if isinstance(schema, list):
        return set().union(*(_deps(x) for x in schema)) if schema else set()
    return set()


def ordered(defs: dict[str, dict]) -> list[str]:
    """Def names, dependencies first (then by name), so no forward reference is needed."""
    out: list[str] = []
    todo = sorted(defs)
    while todo:  # bounded: each pass places at least one def (the schema has no cycles)
        ready = [n for n in todo if _deps(defs[n]) <= set(out)]
        assert ready, "cyclic defs"
        out.append(ready[0])
        todo.remove(ready[0])
    return out


def _union(parts: list[str], sep: str) -> str:
    return sep.join(dict.fromkeys(parts))


def py_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "enum" in s:
        return "Literal[" + ", ".join(json.dumps(v) for v in s["enum"]) + "]"
    if "anyOf" in s:
        return _union([py_type(x) for x in s["anyOf"]], " | ")
    kind = s.get("type")
    simple = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
    if kind in simple:
        return simple[kind]
    if kind == "array":
        return f"list[{py_type(s['items'])}]"
    if kind == "object" and "properties" not in s:
        ap = s.get("additionalProperties")
        return f"dict[str, {py_type(ap)}]" if isinstance(ap, dict) else "dict[str, Any]"
    return "Any"


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "enum" in s:
        return _union([json.dumps(v) for v in s["enum"]], " | ")
    if "anyOf" in s:
        return _union([ts_type(x) for x in s["anyOf"]], " | ")
    kind = s.get("type")
    simple = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}
    if kind in simple:
        return simple[kind]
    if kind == "array":
        inner = ts_type(s["items"])
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object" and "properties" not in s:
        ap = s.get("additionalProperties")
        return f"Record<string, {ts_type(ap)}>" if isinstance(ap, dict) else "Record<string, unknown>"
    return "unknown"


def _wrap(prefix: str, items: list[str], close: str, width: int = 112) -> list[str]:
    lines, cur = [], "    "
    for item in items:
        piece = item + ", "
        if len(cur) + len(piece) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = "    "
        cur += piece
    lines.append(cur.rstrip().rstrip(","))
    return [prefix, *lines, close]


def gen_python(schema: dict) -> str:
    defs = schema["$defs"]
    doc = (f'"""{HEADER}\n\nTyped views of the NI wire contract (ni_schema.json): Literals for the closed vocabularies and\n'
           'TypedDicts for the board row, the flow field and the recipe block."""')
    out = [doc, "",
           "from __future__ import annotations", "", "from typing import Any, Literal, NotRequired, TypedDict"]
    for name in ordered(defs):
        d = defs[name]
        out.append("")
        if "enum" in d or "anyOf" in d or d.get("type") != "object" or "properties" not in d:
            if "enum" in d:
                out += _wrap(f"{name} = Literal[", [json.dumps(v) for v in d["enum"]], "]")
            else:
                out.append(f"{name} = {py_type(d)}")
            continue
        fields = {k: (py_type(v) if k in d["required"] else f"NotRequired[{py_type(v)}]")
                  for k, v in d["properties"].items()}
        if all(k.isidentifier() and not keyword.iskeyword(k) for k in fields):
            out.append(f"class {name}(TypedDict):")
            out += [f"    {k}: {t}" for k, t in fields.items()]
        else:  # a key that is a Python keyword needs the functional form
            out.append(f"{name} = TypedDict(\"{name}\", {{")
            out += [f'    "{k}": {t},' for k, t in fields.items()]
            out.append("})")
    return "\n".join(out).replace("\n\n\n\n", "\n\n\n") + "\n"


def gen_ts(schema: dict) -> str:
    defs = schema["$defs"]
    out = [f"// {HEADER}", "// Types of the NI wire contract (app/smartbrain_3000/ni_schema.json).", ""]
    for name in ordered(defs):
        d = defs[name]
        if d.get("description"):
            out.append(f"/** {d['description']} */")
        if "enum" in d:
            out.append(f"export const {_const(name)} = [{', '.join(json.dumps(v) for v in d['enum'])}] as const;")
            out.append(f"export type {name} = (typeof {_const(name)})[number];")
        elif d.get("type") == "object" and "properties" in d:
            out.append(f"export interface {name} {{")
            for k, v in d["properties"].items():
                key = k if k.isidentifier() else json.dumps(k)
                out.append(f"  {key}{'' if k in d['required'] else '?'}: {ts_type(v)};")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(d)};")
        out.append("")
    return "\n".join(out)


def _const(name: str) -> str:
    """ActionKind -> ACTION_KINDS (the const array beside the union type)."""
    snake = "".join(("_" + c if c.isupper() and i else c) for i, c in enumerate(name)).upper()
    return snake + "S"


def outputs() -> dict[Path, str]:
    schema = build_schema()
    return {OUT_SCHEMA: json.dumps(schema, indent=2, sort_keys=False) + "\n", OUT_PY: gen_python(schema),
            OUT_TS: gen_ts(schema)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, content in outputs().items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(path)
        if not check:
            path.write_text(content)
    if check and stale:
        names = ", ".join(str(p.relative_to(ROOT) if p.is_relative_to(ROOT) else p) for p in stale)
        print(f"stale generated NI schema files: {names}\nRun 'python tools/gen-ni-schema.py' and commit them.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
